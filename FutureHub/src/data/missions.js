// Função para obter missões de uma área específica
export const getMissionsByArea = (areaId) => {
  return MISSIONS[areaId] || [];
};

// Função para obter uma missão aleatória de uma área
export const getRandomMission = (areaId, excludeIds = []) => {
  const missions = getMissionsByArea(areaId);
  const availableMissions = missions.filter(m => !excludeIds.includes(m.id));
  
  if (availableMissions.length === 0) {
    return missions[Math.floor(Math.random() * missions.length)];
  }
  
  return availableMissions[Math.floor(Math.random() * availableMissions.length)];
};
